import { LIMITS, type Limits } from './limits'
import { petLimit, type Tier } from './tiers'

/** The limits the database enforces, in the JSON shape `registry.limits()` returns. */
export type SqlLimits = Limits & { tierLimits: Record<Tier, number | null> }

/** Every domain limit plus the per-tier pet limits (`null` means unlimited). */
export function sqlLimits(): SqlLimits {
  return {
    ...LIMITS,
    tierLimits: { free: petLimit('free'), pro: petLimit('pro'), max: petLimit('max') },
  }
}

/** The migration that first defines `registry.limits()`. It shipped, so it is never rewritten. */
export const FIRST_LIMITS_MIGRATION = '20261023000000_limits.sql'

/** A migration file: its name (`<version>_<name>.sql`) and its SQL. */
export type Migration = { name: string; sql: string }

/** The definition of `registry.limits()` with the current limits, as every limits migration has it. */
function limitsFunctionSql(): string {
  const json = JSON.stringify(sqlLimits(), null, 2).replaceAll("'", "''")
  return `create or replace function registry.limits()
returns jsonb
language sql
immutable
parallel safe
set search_path = ''
as $$
  select '${json}'::jsonb
$$;

comment on function registry.limits() is
  'Domain limits shared with packages/core. Generated; see packages/core/src/sqlLimits.ts.';
`
}

/**
 * The first migration that defines `registry.limits()` (FIRST_LIMITS_MIGRATION), as it shipped.
 * It runs before the schema migration, so it creates the `registry` schema itself.
 */
export function limitsMigrationSql(): string {
  return `-- Generated by \`pnpm gen:sql-limits\` from packages/core (LIMITS and petLimit).
-- Do not edit by hand: packages/core/src/sqlLimits.test.ts fails when this file drifts.
create schema if not exists registry;

${limitsFunctionSql()}`
}

/**
 * A later migration that redefines `registry.limits()` with the current limits: what
 * `pnpm gen:sql-limits` writes as a new file when LIMITS or the tier pet limits change (Ruling 15).
 * It also brings the pet-photos bucket's size cap up to date: 20261023000006_photo_api.sql read it
 * from `registry.limits()` once, when it made the bucket.
 */
export function limitsUpdateMigrationSql(): string {
  return `-- Generated by \`pnpm gen:sql-limits\` from packages/core (LIMITS and petLimit): the limits
-- changed after the earlier limits migrations shipped, and those are never edited (Ruling 15).
-- Do not edit by hand: packages/core/src/sqlLimits.test.ts fails when the newest migration that
-- defines registry.limits() drifts.
${limitsFunctionSql()}
-- The bucket's size cap was read from registry.limits() when 20261023000006_photo_api.sql made it.
update storage.buckets
   set file_size_limit = (registry.limits() ->> 'photoMaxBytes')::bigint
 where id = 'pet-photos';
`
}

/** What each limits migration says, whichever one it is: the first, or a later one. */
export function expectedLimitsMigrationSql(name: string): string {
  return name === FIRST_LIMITS_MIGRATION ? limitsMigrationSql() : limitsUpdateMigrationSql()
}

const DEFINES_LIMITS = /create\s+or\s+replace\s+function\s+registry\.limits\s*\(/i

/**
 * The migration whose definition of `registry.limits()` a database ends up with: the last one,
 * in the order Supabase applies them (file name order), that defines it.
 */
export function newestLimitsMigration(migrations: readonly Migration[]): Migration | undefined {
  return [...migrations]
    .sort((a, b) => (a.name < b.name ? 1 : a.name > b.name ? -1 : 0))
    .find((migration) => DEFINES_LIMITS.test(migration.sql))
}

const pad = (n: number, width = 2) => String(n).padStart(width, '0')

/**
 * The version (the file name's leading `YYYYMMDDHHMMSS`) for a new migration: `now` in UTC, or one
 * after the newest existing version if that is later, so the new file is always applied last.
 */
export function nextMigrationVersion(existing: readonly string[], now: Date): string {
  const clock =
    `${pad(now.getUTCFullYear(), 4)}${pad(now.getUTCMonth() + 1)}${pad(now.getUTCDate())}` +
    `${pad(now.getUTCHours())}${pad(now.getUTCMinutes())}${pad(now.getUTCSeconds())}`
  const latest = existing
    .map((name) => /^(\d{14})_/.exec(name)?.[1])
    .filter((version): version is string => version !== undefined)
    .sort()
    .at(-1)
  return latest === undefined || clock > latest ? clock : String(BigInt(latest) + 1n)
}
