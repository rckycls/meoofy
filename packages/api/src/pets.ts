import {
  AppError,
  petInputSchema,
  petPatchSchema,
  type PetInput,
  type PetPatch,
  type Species,
} from '@meoofy/core'
import type { MeoofyClient } from './client'
import type { Database } from './database.types'
import { toAppError, withStatus } from './errors'
import { parseId, validationError } from './validation'

/** The api.pets columns PET_COLUMNS selects (create_pet and update_pet return more). */
type PetRow = Omit<Database['api']['Views']['pets']['Row'], 'updated_at'>
type CreatePetArgs = Database['api']['Functions']['create_pet']['Args']
type UpdatePetArgs = Database['api']['Functions']['update_pet']['Args']

export type Pet = {
  id: string
  name: string
  species: Species
  breed: string | null
  /** Approximate age in whole months, or `null` when unknown. */
  ageMonths: number | null
  /** Only `private` pets count against the plan's pet limit. */
  registrationState: 'private' | 'archived'
  discoveryEnabled: boolean
  createdAt: string
}

const PET_COLUMNS =
  'id, name, species, breed, age_months, registration_state, discovery_enabled, created_at'

// Postgres reports every view column as nullable, so the generated row type does too. The columns
// checked below are NOT NULL in registry.pets; a null there means the view changed underneath us.
function toPet(row: PetRow): Pet {
  const { id, name, species, registration_state, created_at } = row
  if (
    id === null ||
    name === null ||
    species === null ||
    registration_state === null ||
    created_at === null
  ) {
    throw new AppError('UNKNOWN', 'api.pets returned a row with a missing column')
  }
  return {
    id,
    name,
    species,
    breed: row.breed,
    ageMonths: row.age_months,
    registrationState: registration_state,
    discoveryEnabled: row.discovery_enabled ?? false,
    createdAt: created_at,
  }
}

/** The signed-in owner's pets, oldest first. */
export async function listPets(c: MeoofyClient): Promise<Pet[]> {
  try {
    const { data, error, status } = await c
      .from('pets')
      .select(PET_COLUMNS)
      .order('created_at', { ascending: true })
      .order('id', { ascending: true })
    if (error) throw withStatus(error, status)
    return data.map(toPet)
  } catch (e) {
    throw toAppError(e)
  }
}

/**
 * One of the signed-in owner's pets, or `null` when they have none with that id (someone else's
 * pet reads as `null` too). An id that is not a uuid rejects with VALIDATION.
 */
export async function getPet(c: MeoofyClient, id: string): Promise<Pet | null> {
  try {
    const petId = parseId(id)
    const { data, error, status } = await c
      .from('pets')
      .select(PET_COLUMNS)
      .eq('id', petId)
      .maybeSingle()
    if (error) throw withStatus(error, status)
    return data === null ? null : toPet(data)
  } catch (e) {
    throw toAppError(e)
  }
}

/**
 * Creates a private pet. The id is generated by the caller, so a retry with the same id returns
 * the pet the first call created (unchanged) instead of a second one. At the plan's limit it
 * rejects with PET_LIMIT_REACHED; the server serialises one owner's creates, so a double tap
 * can't slip past the limit.
 */
export async function createPet(c: MeoofyClient, input: PetInput): Promise<Pet> {
  try {
    const parsed = petInputSchema.safeParse(input)
    if (!parsed.success) throw validationError(parsed.error)
    const { id, name, species, breed, ageMonths } = parsed.data
    // Postgres can't mark a function argument NOT NULL, yet the generator types each one as
    // required and non-null. create_pet takes null for an unknown breed or age.
    const args: { [K in keyof CreatePetArgs]: CreatePetArgs[K] | null } = {
      id,
      name,
      species,
      breed,
      age_months: ageMonths,
    }
    const { data, error, status } = await c.rpc('create_pet', args as CreatePetArgs)
    if (error) throw withStatus(error, status)
    return toPet(data)
  } catch (e) {
    throw toAppError(e)
  }
}

/**
 * Changes the given fields of one of the owner's pets. An absent field is left as it is; `null`
 * (or an empty breed) clears breed or age. Someone else's pet, or one that doesn't exist, rejects
 * with NOT_OWNER.
 */
export async function updatePet(c: MeoofyClient, id: string, patch: PetPatch): Promise<Pet> {
  try {
    const petId = parseId(id)
    const parsed = petPatchSchema.safeParse(patch)
    if (!parsed.success) throw validationError(parsed.error)
    const { name, species, breed, ageMonths } = parsed.data
    // update_pet leaves a field unchanged when its argument is missing, and clears breed and age
    // only through the explicit clear flags.
    const args: UpdatePetArgs = { id: petId }
    if (name !== undefined) args.name = name
    if (species !== undefined) args.species = species
    if (breed === null) args.clear_breed = true
    else if (breed !== undefined) args.breed = breed
    if (ageMonths === null) args.clear_age = true
    else if (ageMonths !== undefined) args.age_months = ageMonths
    const { data, error, status } = await c.rpc('update_pet', args)
    if (error) throw withStatus(error, status)
    return toPet(data)
  } catch (e) {
    throw toAppError(e)
  }
}

/**
 * Deletes one of the owner's pets with all its photos (their files are queued for cleanup).
 * Resolves when the pet is already gone, so a retried delete succeeds (Ruling 18).
 */
export async function deletePet(c: MeoofyClient, id: string): Promise<void> {
  try {
    const petId = parseId(id)
    const { error, status } = await c.rpc('delete_pet', { id: petId })
    if (error) throw withStatus(error, status)
  } catch (e) {
    const appError = toAppError(e)
    // The server answers NOT_OWNER for a pet the caller can't see: deleted already (say the first
    // answer was lost), or never theirs. Either way there is no pet of theirs left to delete.
    if (appError.code === 'NOT_OWNER') return
    throw appError
  }
}
