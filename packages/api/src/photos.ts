import { AppError, LIMITS, photoRequestSchema, type PhotoView } from '@pawpin/core'
import type { PawpinClient } from './client'
import type { Database } from './database.types'
import { toAppError, withStatus } from './errors'
import { parseId, validationError } from './validation'

type PhotoRow = Database['api']['Views']['pet_photos']['Row']

export type PetPhoto = {
  id: string
  petId: string
  view: PhotoView
  status: 'pending' | 'ready' | 'rejected'
  /** Pixel size as confirmed; 0 until the photo is confirmed. */
  width: number
  height: number
  /** A URL to display a `ready` photo, valid for LIMITS.signedUrlSeconds; otherwise `null`. */
  signedUrl: string | null
}

/** A photo to upload: the prepared JPEG plus what the device measured on it. */
export type PhotoUpload = {
  /** Generated by the caller, fresh for each new photo; reused only to retry the same photo. */
  id: string
  petId: string
  view: PhotoView
  jpeg: ArrayBuffer
  width: number
  height: number
  blurScore: number
  brightness: number
}

const BUCKET = 'pet-photos'
const PHOTO_COLUMNS = 'id, pet_id, view, status, width, height, storage_path'

type PhotoFields = Pick<PhotoRow, 'id' | 'pet_id' | 'view' | 'status' | 'width' | 'height'>

// Postgres reports every view column as nullable, so the generated row type does too. The columns
// checked below are NOT NULL in registry.pet_photos; width and height stay null until confirmed.
function toPetPhoto(row: PhotoFields, signedUrl: string | null): PetPhoto {
  const { id, pet_id, view, status } = row
  if (id === null || pet_id === null || view === null || status === null) {
    throw new AppError('UNKNOWN', 'api.pet_photos returned a row with a missing column')
  }
  return {
    id,
    petId: pet_id,
    view,
    status,
    width: row.width ?? 0,
    height: row.height ?? 0,
    signedUrl,
  }
}

/** A signed URL for one file, or `null` if Storage won't make one right now. */
async function signedUrlOrNull(c: PawpinClient, path: string): Promise<string | null> {
  try {
    const { data } = await c.storage.from(BUCKET).createSignedUrl(path, LIMITS.signedUrlSeconds)
    return data?.signedUrl ?? null
  } catch {
    return null
  }
}

/**
 * Storage's answer when a file already exists at the path (sent as HTTP 400 with statusCode
 * "409", error "Duplicate", code "KeyAlreadyExists").
 */
function isDuplicate(error: { statusCode?: string } & object): boolean {
  return error.statusCode === '409' || ('code' in error && error.code === 'KeyAlreadyExists')
}

/**
 * A pet's photos (every status), oldest first. Ready photos carry a signed URL valid for
 * LIMITS.signedUrlSeconds (one hour); a ready photo whose file Storage can't sign has `null`.
 */
export async function listPhotos(c: PawpinClient, petId: string): Promise<PetPhoto[]> {
  try {
    const pet = parseId(petId, 'petId')
    const { data, error, status } = await c
      .from('pet_photos')
      .select(PHOTO_COLUMNS)
      .eq('pet_id', pet)
      .order('created_at', { ascending: true })
      .order('id', { ascending: true })
    if (error) throw withStatus(error, status)

    const readyPaths = data.flatMap((row) =>
      row.status === 'ready' && row.storage_path !== null ? [row.storage_path] : [],
    )
    const urls = new Map<string, string>()
    if (readyPaths.length > 0) {
      const signed = await c.storage
        .from(BUCKET)
        .createSignedUrls(readyPaths, LIMITS.signedUrlSeconds)
      if (signed.error) throw signed.error
      for (const { path, signedUrl, error: fileError } of signed.data) {
        if (path !== null && signedUrl !== null && fileError === null) urls.set(path, signedUrl)
      }
    }

    return data.map((row) =>
      toPetPhoto(
        row,
        row.status === 'ready' && row.storage_path !== null
          ? (urls.get(row.storage_path) ?? null)
          : null,
      ),
    )
  } catch (e) {
    throw toAppError(e)
  }
}

/**
 * The photo `a.id` if it is already confirmed as this pet's `a.view`: what a retry finds when the
 * first attempt's confirm got through but its answer was lost.
 */
async function alreadyConfirmed(c: PawpinClient, a: PhotoUpload): Promise<PetPhoto | null> {
  const { data, error, status } = await c
    .from('pet_photos')
    .select(PHOTO_COLUMNS)
    .eq('id', a.id)
    .maybeSingle()
  if (error) throw withStatus(error, status)
  if (
    data === null ||
    data.status !== 'ready' ||
    data.pet_id !== a.petId ||
    data.view !== a.view ||
    data.storage_path === null
  ) {
    return null
  }
  return toPetPhoto(data, await signedUrlOrNull(c, data.storage_path))
}

const isPositiveInteger = (n: number) => Number.isInteger(n) && n > 0

/**
 * Uploads a reference photo: asks the server for an upload slot, uploads the JPEG to the private
 * bucket at the slot's path, then confirms it, which makes it the pet's photo for its view (a
 * front, side or markings photo replaces the previous one).
 *
 * Retrying with the same id is safe at every step: a file already uploaded is not sent twice,
 * and a photo already confirmed is returned as it is. A confirm the server refuses (the photo is
 * missing or too small) rejects with PHOTO_QUALITY and leaves the photo `pending`, so it can be
 * retried. The quality checks on the image itself (`assessPhoto`) run on the device first.
 */
export async function uploadPhoto(c: PawpinClient, a: PhotoUpload): Promise<PetPhoto> {
  try {
    const request = photoRequestSchema.safeParse({
      id: a.id,
      petId: a.petId,
      view: a.view,
      contentType: 'image/jpeg',
      bytes: a.jpeg.byteLength,
    })
    if (!request.success) throw validationError(request.error)
    if (!isPositiveInteger(a.width) || !isPositiveInteger(a.height)) {
      throw new AppError('VALIDATION', 'width and height must be whole pixels above 0')
    }
    if (!Number.isFinite(a.blurScore) || !Number.isFinite(a.brightness)) {
      throw new AppError('VALIDATION', 'blurScore and brightness must be finite numbers')
    }
    const { id, petId, view, contentType, bytes } = request.data

    const slot = await c.rpc('request_photo_upload', {
      id,
      pet_id: petId,
      view,
      content_type: contentType,
      bytes,
    })
    if (slot.error) {
      // The server refuses a slot for an id that is no longer pending (VALIDATION). If that is
      // because this very photo was confirmed, the retry has nothing left to do.
      const refusal = toAppError(withStatus(slot.error, slot.status))
      const done = refusal.code === 'VALIDATION' ? await alreadyConfirmed(c, a) : null
      if (done !== null) return done
      throw refusal
    }
    const path = slot.data

    // Ruling 21: a plain upload, never upsert or a signed upload URL, so nothing already stored
    // can be overwritten. A file already at the path is this photo's, from an earlier attempt.
    const upload = await c.storage
      .from(BUCKET)
      .upload(path, a.jpeg, { contentType: 'image/jpeg', upsert: false })
    if (upload.error && !isDuplicate(upload.error)) throw upload.error

    const confirmed = await c.rpc('confirm_photo', {
      id,
      width: a.width,
      height: a.height,
      blur_score: a.blurScore,
      brightness: a.brightness,
    })
    if (confirmed.error) throw withStatus(confirmed.error, confirmed.status)

    // The photo is saved now; failing to sign its URL must not fail the upload.
    return toPetPhoto(confirmed.data, await signedUrlOrNull(c, path))
  } catch (e) {
    throw toAppError(e)
  }
}

/**
 * Deletes one of the owner's photos (its file is queued for cleanup). Resolves when the photo is
 * already gone, so a retried delete succeeds, as deletePet does (Ruling 18).
 */
export async function deletePhoto(c: PawpinClient, id: string): Promise<void> {
  try {
    const photoId = parseId(id)
    const { error, status } = await c.rpc('delete_photo', { id: photoId })
    if (error) throw withStatus(error, status)
  } catch (e) {
    const appError = toAppError(e)
    if (appError.code === 'NOT_OWNER') return
    throw appError
  }
}
